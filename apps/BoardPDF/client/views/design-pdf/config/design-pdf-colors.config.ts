function formatGradientLabel(gradientCss: string): string {
  const angleMatch = gradientCss.match(/(\d+(?:\.\d+)?)deg/i);
  const hexes = gradientCss.match(/#[a-f0-9]{6}|#[a-f0-9]{3}/gi) || [];
  const angleSuffix = angleMatch ? ` · ${angleMatch[1]}°` : '';
  return `${hexes.join(' → ')}${angleSuffix}`;
}

